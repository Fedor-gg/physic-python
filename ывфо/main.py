# Задача 8: Амплитудная модуляция (Принцип радиосвязи)
# ============================================================
def task_8():
    print("\n" + "=" * 60)
    print("Задача 8: Амплитудная модуляция")
    print("=" * 60)

    # Данные
    A_c = 10.0  # 10 В
    nu_c = 1e6  # 1 МГц
    A_m = 4.0  # 4 В
    nu_m = 1e3  # 1 кГц

    # Коэффициент модуляции
    M = A_m / A_c

    # Частоты в спектре
    nu_lower = nu_c - nu_m
    nu_upper = nu_c + nu_m

    # Огибающая
    envelope_max = A_c * (1 + M)
    envelope_min = A_c * (1 - M)

    print(f"Коэффициент модуляции M: {M:.2f}")
    print(f"Частоты в спектре сигнала:")
    print(f"  Несущая: {nu_c / 1e6:.3f} МГц")
    print(f"  Верхняя боковая: {nu_upper / 1e6:.6f} МГц ({nu_upper:.1f} Гц)")
    print(f"  Нижняя боковая: {nu_lower / 1e6:.6f} МГц ({nu_lower:.1f} Гц)")
    print(f"Максимальное значение огибающей: {envelope_max:.2f} В")
    print(f"Минимальное значение огибающей: {envelope_min:.2f} В")


