# Задача 5: Затухающие колебания и логарифмический декремент
# ============================================================
def task_5():
    print("\n" + "=" * 60)
    print("Задача 5: Затухающие колебания")
    print("=" * 60)

    L = 20e-3  # 20 мГн
    C = 2e-6  # 2 мкФ
    R = 5.0  # 5 Ом

    R_cr = 2 * math.sqrt(L / C)
    print(f"Критическое сопротивление R_cr: {R_cr:.2f} Ом")
    print(f"Дано R: {R} Ом")

    if R < R_cr:
        print("Колебания возможны? Да")
    else:
        print("Колебания возможны? Нет (апериодический режим)")
        return

    beta = R / (2 * L)
    omega0_sq = 1 / (L * C)
    omega = math.sqrt(omega0_sq - beta ** 2)
    T = 2 * math.pi / omega

    print(f"Период затухающих колебаний T: {T * 1000:.2f} мс")

    delta = R * T / (2 * L)
    print(f"Логарифмический декремент δ: {delta:.4f}")

    ratio = math.exp(delta)
    print(f"Амплитуда уменьшится за период в {ratio:.2f} раз(а)")

    print(f"\n(Проверка: δ = β·T = {beta:.2f} × {T:.4f} = {delta:.4f})")
    print(f"Добротность Q = π/δ = {math.pi / delta:.2f}")


