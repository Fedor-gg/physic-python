# Задача 7: Резонанс напряжений в последовательной цепи
# ============================================================
def task_7():
    print("\n" + "=" * 60)
    print("Задача 7: Резонанс напряжений")
    print("=" * 60)

    L = 0.5  # 0.5 Гн
    C = 20e-6  # 20 мкФ
    R = 10.0  # 10 Ом
    U = 220.0  # 220 В

    omega_res = 1 / math.sqrt(L * C)
    nu_res = omega_res / (2 * math.pi)
    I_res = U / R
    X_C = 1 / (omega_res * C)
    U_C = I_res * X_C
    Q_factor = X_C / R

    print(f"Резонансная частота ν_res: {nu_res:.2f} Гц")
    print(f"Сила тока при резонансе I_res: {I_res:.2f} А")
    print(f"Напряжение на конденсаторе U_C: {U_C:.2f} В")
    print(f"Добротность контура (превышение напряжения): {Q_factor:.2f} раз(а)")
    print(f"Примечание: Напряжение на элементах реактивной цепи может превышать напряжение источника!")


