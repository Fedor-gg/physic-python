# Задача 6: Мгновенные значения энергии
# ============================================================
def task_6():
    print("\n" + "=" * 60)
    print("Задача 6: Мгновенные значения энергии")
    print("=" * 60)

    Qm = 2e-6  # 2·10⁻⁶ Кл
    omega = 1e4  # 10⁴ рад/с
    C = 1e-6  # 1 мкФ
    t = math.pi / (4 * omega)

    print(f"Исходные данные:")
    print(f"  Qm = {Qm * 1e6:.1f} мкКл, ω = {omega:.0e} рад/с, C = {C * 1e6:.0f} мкФ")
    print(f"  t = π/(4ω) = {t:.6f} с\n")

    Im = Qm * omega
    print(f"Амплитуда тока I_max: {Im * 1000:.2f} мА")

    W = (Qm ** 2) / (2 * C)
    print(f"Полная энергия контура W: {W * 1e6:.2f} мкДж")

    sin_val = math.sin(omega * t)
    sin_sq = sin_val ** 2
    cos_val = math.cos(omega * t)
    cos_sq = cos_val ** 2

    WL = W * sin_sq
    WC = W * cos_sq

    print(f"\nВ момент t = π/(4ω):")
    print(f"  Энергия магнитного поля W_L: {WL * 1e6:.2f} мкДж")
    print(f"  Энергия электрического поля W_C: {WC * 1e6:.2f} мкДж")
    print(f"  Сумма (проверка): {WL * 1e6 + WC * 1e6:.2f} мкДж")

    print(f"\n(Детали расчёта:)")
    print(f"  ωt = π/4 = {math.pi / 4:.4f} рад")
    print(f"  sin²(ωt) = sin²(π/4) = {sin_sq:.4f}")
    print(f"  cos²(ωt) = cos²(π/4) = {cos_sq:.4f}")
    print(f"  W_L = W·sin² = {W * 1e6:.2f} × {sin_sq:.2f} = {WL * 1e6:.2f} мкДж")
    print(f"  W_C = W·cos² = {W * 1e6:.2f} × {cos_sq:.2f} = {WC * 1e6:.2f} мкДж")
    print(f"  W_L + W_C = {WL * 1e6 + WC * 1e6:.2f} мкДж = W")


