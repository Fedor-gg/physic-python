# ============================================================================
print("\n" + "=" * 60)
print("Задача 3. Настройка контура на длину волны")
print("λ = c·2π√(L·C) → C = λ²/(4π²c²L)")
print("=" * 60)

# Входные данные
lambda_wave = 300.0      # длина волны, м
L_mH = 10.0              # индуктивность, мГн
c = 3e8                  # скорость света, м/с

# Перевод в СИ: 1 мГн = 10^(-3) Гн
L = L_mH * 1e-3

# Расчёт ёмкости из формулы λ = c·2π√(L·C)
# Выражаем C: C = λ² / (4π²c²L)
C = lambda_wave**2 / (4 * math.pi**2 * c**2 * L)

# Перевод в пикофарады (1 пФ = 10^(-12) Ф)
C_pF = C * 1e12

# Вывод результатов
print(f"\nИсходные данные:")
print(f"  Длина волны λ = {lambda_wave} м")
print(f"  Индуктивность L = {L_mH} мГн = {L:.2e} Гн")
print(f"  Скорость света c = {c:.0e} м/с")

print(f"\nРЕЗУЛЬТАТЫ:")
print(f"  Необходимая ёмкость C = {C:.2e} Ф")
print(f"  Емкость в пикофарадах = {C_pF:.2f} пФ")

# Проверка с эталонными значениями
C_expected = 2.53e-12
C_pF_expected = 2.53

print(f"\nСравнение с эталоном:")
print(f"  C = {C:.2e} Ф (эталон: {C_expected:.2e} Ф)")
print(f"  C = {C_pF:.2f} пФ (эталон: {C_pF_expected:.2f} пФ)")

# Проверка: расчёт длины волны по найденной ёмкости
lambda_check = c * 2 * math.pi * math.sqrt(L * C)
print(f"\nПроверка: λ = c·2π√(L·C) = {lambda_check:.1f} м (должно быть {lambda_wave} м) ✓")

