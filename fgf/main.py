print("=" * 60)
print("Задача 1. Расчёт периода и частоты колебаний")
print("Формула Томсона: T = 2π√(L·C)")
print("=" * 60)

# Входные данные
C_microfarad = 2.0   # ёмкость, мкФ (микрофарады)
L = 0.5              # индуктивность, Гн

# Перевод в СИ: 1 мкФ = 10^(-6) Ф
C = C_microfarad * 1e-6

# Расчёт периода по формуле Томсона
T = 2 * math.pi * math.sqrt(L * C)

# Расчёт частоты
nu = 1 / T

# Вывод результатов
print(f"\nИсходные данные:")
print(f"  Ёмкость C = {C_microfarad} мкФ = {C:.2e} Ф")
print(f"  Индуктивность L = {L} Гн")

print(f"\nРЕЗУЛЬТАТЫ:")
print(f"  Период T = {T:.4f} с")
print(f"  Частота ν = {nu:.2f} Гц")

# Проверка с указанными в условии значениями
