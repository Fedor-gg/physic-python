# ЗАДАЧА 2. Превращение энергии в колебательном контуре
# ============================================================================
print("\n" + "=" * 60)
print("Задача 2. Энергия в колебательном контуре")
print("W = C·U²/2 = L·I²/2")
print("=" * 60)

# Входные данные
U_max = 100.0        # максимальное напряжение на конденсаторе, В
C_microfarad = 10.0  # ёмкость, мкФ
L = 0.1              # индуктивность, Гн

# Перевод в СИ
C = C_microfarad * 1e-6

# Расчёт полной энергии (через конденсатор)
W = (C * U_max**2) / 2

# Расчёт амплитуды тока (через полную энергию)
I_max = math.sqrt(2 * W / L)

# Альтернативный расчёт амплитуды тока по формуле I_max = U_max·√(C/L)
I_max_alt = U_max * math.sqrt(C / L)

# Вывод результатов
print(f"\nИсходные данные:")
print(f"  Максимальное напряжение U_max = {U_max} В")
print(f"  Ёмкость C = {C_microfarad} мкФ = {C:.2e} Ф")
print(f"  Индуктивность L = {L} Гн")

print(f"\nРЕЗУЛЬТАТЫ:")
print(f"  Полная энергия поля W = {W:.4f} Дж")
print(f"  Амплитуда силы тока I_max = {I_max:.4f} А")

# Проверка с альтернативной формулой
print(f"\nПроверка:")
print(f"  I_max (через U_max·√(C/L)) = {I_max_alt:.4f} А ✓")

# Сравнение с эталонными значениями
W_expected = 0.0500
