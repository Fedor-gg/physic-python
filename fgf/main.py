print(f"  I_max = {I_max:.4f} А (эталон: {I_max_expected:.4f} А)")

# Дополнительное пояснение
print(f"\nПояснение:")
print(f"  Энергия электрического поля: W_C = C·U_max²/2 = {W:.4f} Дж")
print(f"  Энергия магнитного поля: W_L = L·I_max²/2 = {L * I_max**2 / 2:.4f} Дж")
print(f"  W_C = W_L → энергия переходит из конденсатора в катушку и обратно")

