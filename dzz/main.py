import math

# ============================================================================
# ЗАДАЧА 1. Пружинный маятник
# ============================================================================
print("=" * 60)
print("Задача 1. Пружинный маятник")
print("=" * 60)

# Входные данные
m = 0.2      # масса груза, кг
k = 50.0     # жёсткость пружины, Н/м
A = 0.05     # амплитуда колебаний, м

# Расчёт периода (формула: T = 2π·√(m/k))
T = 2 * math.pi * math.sqrt(m / k)

# Расчёт частоты (ν = 1/T)
nu = 1 / T

# Расчёт циклической частоты (ω = √(k/m))
omega = math.sqrt(k / m)

# Расчёт энергии
# Полная механическая энергия = максимальная потенциальная = k·A²/2
E_max_potential = (k * A**2) / 2
# Максимальная кинетическая энергия равна полной энергии
E_max_kinetic = E_max_potential

# Вывод результатов
print("\nИсходные данные:")
print(f"  Масса груза m = {m} кг")
print(f"  Жёсткость пружины k = {k} Н/м")
print(f"  Амплитуда A = {A} м")

print("\nРЕЗУЛЬТАТЫ:")
print(f"  1. Период T = {T:.4f} с")
print(f"  2. Частота ν = {nu:.2f} Гц")
print(f"  3. Циклическая частота ω = {omega:.2f} рад/с")
print(f"  4. Максимальная кинетическая энергия = {E_max_kinetic:.4f} Дж")
print(f"     Максимальная потенциальная энергия = {E_max_potential:.4f} Дж")

# Дополнительная проверка через максимальную скорость
v_max = A * omega
E_kin_check = 0.5 * m * v_max**2
print(f"\nПроверка: максимальная скорость v_max = {v_max:.3f} м/с")
print(f"  E_kin_max = m·v_max²/2 = {E_kin_check:.4f} Дж ✓")

# ============================================================================
# ЗАДАЧА 2. Математический маятник
# ============================================================================
print("\n" + "=" * 60)
print("Задача 2. Математический маятник")
print("=" * 60)

# ---------------------------------------------------------------
# Часть А: Расчёт периода по известным L и g
# ---------------------------------------------------------------
L = 1.0      # длина нити, м
g = 9.81     # ускорение свободного падения, м/с²

T_calculated = 2 * math.pi * math.sqrt(L / g)

print("\n--- Часть А: Расчёт периода по длине ---")
print(f"  Длина нити L = {L} м")
print(f"  Ускорение g = {g} м/с²")
print(f"  Рассчитанный период T = {T_calculated:.4f} с")

# ---------------------------------------------------------------
# Часть Б: Определение g по измеренным T и L
# ---------------------------------------------------------------
T_measured = 2.0    # измеренный период, с
L_measured = 0.99   # измеренная длина, м

# Из формулы T = 2π·√(L/g) выражаем g = 4π²·L / T²
g_calculated = (4 * math.pi**2 * L_measured) / (T_measured**2)

print("\n--- Часть Б: Определение g по периоду ---")
print(f"  Измеренный период T = {T_measured} с")
print(f"  Измеренная длина L = {L_measured} м")
print(f"  Вычисленное ускорение g = {g_calculated:.4f} м/с²")

# Сравнение с истинным значением
g_true = 9.81
error = abs(g_calculated - g_true) / g_true * 100
print(f"  Относительная погрешность = {error:.2f}%")

